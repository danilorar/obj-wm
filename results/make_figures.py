"""Re-make the README tables and summary figures from the JSON files in this folder (no dataset, no checkpoint).

    python results/make_figures.py          # needs only matplotlib

Writes results/tables.md, results/figures/closed_loop_summary.png and results/figures/v3_reaction.png.
The qualitative figures (prediction examples, follower test, closed-loop GIF) are stored in results/figures/ as images;
re-making them needs nuScenes and a trained checkpoint (see the README).
"""
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = Path(__file__).resolve().parent
FIG = HERE / "figures"


def load(name):
    return json.loads((HERE / name).read_text())


def closed_loop_table(cl):
    lines = ["| Planner | Other road users | At-fault collisions | Rear-ended | Progress | Time within 1 m of others |",
             "|---|---|---|---|---|---|"]
    for key, label in (("replay", "replay the log"), ("reactive_idm", "react")):
        for p in ("CV", "WM"):
            r = cl["runs"][key]["planners"][p]
            lines.append(f"| {p} | {label} | {r['at_fault']} | {r['rear_ended']} | {r['progress_mean']:.3f} | "
                         f"{100 * r['close_call_share_mean']:.1f}% |")
    d = cl["runs"]["reactive_idm"]["preregistered_decision"]["co_primary"]["close-call share (steps < 1 m)"]
    lines.append("")
    lines.append(f"Pre-registered co-primary (reactive): close-call share WM - CV = {100 * d['mean']:.1f} pp, "
                 f"97.5% CI [{100 * d['ci97_5'][0]:.1f}, {100 * d['ci97_5'][1]:.1f}] pp, Wilcoxon p = {d['wilcoxon_p']:.0e}.")
    return lines


def val_table(val):
    runs = val["runs"]
    seeds = [runs[k]["plan_on"]["minADE6"] for k in ("v2_d_rerun", "v2_d_seed123", "v2_d_seed2026")]
    mean = sum(seeds) / 3
    sd = (sum((s - mean) ** 2 for s in seeds) / 2) ** 0.5
    lines = [f"v2 val target minADE6 (plan on), 3 seeds: {mean:.3f} +- {sd:.3f} m "
             f"({', '.join(f'{s:.3f}' for s in seeds)}).",
             f"Same seed and flags on another machine (control): {runs['v2_d_rerun_current']['plan_on']['minADE6']:.3f} m "
             f"vs {runs['v2_d_rerun']['plan_on']['minADE6']:.3f} m."]
    return lines


def v3_table(v3, val):
    sel, conf, runs = v3["selection_round"], v3["v3a_confirmation"]["seeds"], val["runs"]
    rows = [("v2 seed 42", sel["d_rerun"]), ("v2 seed 123", sel["d_seed123"]), ("v2 seed 2026", sel["d_seed2026"]),
            ("v3a seed 42", conf["v3a"]), ("v3a seed 123", conf["v3a_seed123"]), ("v3a seed 2026", conf["v3a_seed2026"]),
            ("v3b", sel["v3b"]), ("v3c", sel["v3c"])]
    t = v3["thresholds"]
    lines = [f"| Model | Brake ratio (>= {t['brake_ratio_min']}) | Placebo (<= {t['placebo_mean_max']} m) | "
             f"Val minADE6 (<= {t['val_minade6_max']} m) | Specificity |", "|---|---|---|---|---|"]
    for name, r in rows:
        v = r.get("val_minade6", r.get("val"))
        lines.append(f"| {name} | {r['ratio']:.3f} | {r['placebo']:.2f} | {v:.3f} | {r['specificity']:.2f} |")
    lines.append("")
    lines.append(f"v3a 3-seed mean brake ratio {v3['v3a_confirmation']['mean_brake_ratio']:.3f}; "
                 f"confirmed: {v3['v3a_confirmation']['confirmed']}.")
    return lines, rows


def main():
    cl, val, v3, wd = (load("closed_loop_test150.json"), load("val_open_loop.json"), load("v3_follower_placebo.json"),
                       load("womd_av2_feasibility.json"))
    v3_lines, v3_rows = v3_table(v3, val)
    md = ["# Tables (generated by results/make_figures.py)", "", "## Closed loop, 146 test scenes", ""]
    md += closed_loop_table(cl) + ["", "## Open-loop validation", ""] + val_table(val)
    md += ["", "## v3 follower / placebo checks", ""] + v3_lines
    hz = load("hesitation_dev100.json")
    md += ["", "## Planner chatter on dev100 (development scenes)", "",
           "| Other road users | Planner | Accel. sign flips / min | Stop-go / min | Mean abs jerk [m/s^3] |", "|---|---|---|---|---|"]
    for key, label in (("replay", "replay"), ("reactive_idm", "react")):
        for p_ in ("CV", "WM", "expert"):
            r = hz[key][p_]
            md.append(f"| {label} | {p_} | {r['accel_sign_flips_per_min']:.1f} | {r['stop_go_per_min']:.2f} | {r['mean_abs_jerk']:.2f} |")
    md += ["", "## Strong ego-follower braking events per hour", "",
           f"nuScenes {wd['nuscenes']['events_per_h']}, WOMD {wd['womd_val_files_00000_00002']['events_per_h']}, "
           f"Argoverse 2 {wd['argoverse2_val_2000']['events_per_h']} (gate {wd['gate_per_h']}): {wd['decision']}."]
    (HERE / "tables.md").write_text("\n".join(md) + "\n")

    FIG.mkdir(exist_ok=True)
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.4))
    for ax, (key, title) in zip(axes, (("replay", "Other road users replay the log"), ("reactive_idm", "Other road users react"))):
        p = cl["runs"][key]["planners"]
        vals = [100 * p["CV"]["close_call_share_mean"], 100 * p["WM"]["close_call_share_mean"]]
        ax.bar(["CV", "WM"], vals, color=["#9a9a9a", "#2e8b57"])
        for i, v in enumerate(vals):
            ax.text(i, v + 0.2, f"{v:.1f}%", ha="center")
        ax.set_title(title, fontsize=10)
        ax.set_ylabel("time within 1 m of others [%]")
        ax.spines[["top", "right"]].set_visible(False)
    fig.suptitle("Closed loop, 146 test scenes", fontsize=11)
    fig.tight_layout()
    fig.savefig(FIG / "closed_loop_summary.png", dpi=130)

    fig, ax = plt.subplots(figsize=(6, 4))
    for name, r in v3_rows:
        c = "#9a9a9a" if name.startswith("v2") else ("#2e8b57" if name.startswith("v3a") else "#c0504d")
        ax.scatter(r["placebo"], r["ratio"], color=c, s=40)
        ax.annotate(name, (r["placebo"], r["ratio"]), xytext=(4, 3), textcoords="offset points", fontsize=8)
    t = v3["thresholds"]
    ax.axhline(t["brake_ratio_min"], color="k", lw=0.8, ls="--")
    ax.axvline(t["placebo_mean_max"], color="k", lw=0.8, ls="--")
    ax.set_xlabel("placebo: travel change of agents that should not react [m]")
    ax.set_ylabel("follower brake ratio")
    ax.set_title("Reaction to our plan (pass = upper left)", fontsize=10)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(FIG / "v3_reaction.png", dpi=130)
    print(f"wrote {HERE / 'tables.md'}, {FIG / 'closed_loop_summary.png'}, {FIG / 'v3_reaction.png'}")


if __name__ == "__main__":
    main()
